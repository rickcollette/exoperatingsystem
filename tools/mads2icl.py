#!/usr/bin/env python3
"""Turn a MADS label table into an include of equates for other assemblies.

Labels already defined in the given include files (NAME equ ...) are left
out, so both can be included together.

usage: mads2icl.py labels.lab out.icl [exclude.icl ...]
"""
import re
import sys


def main():
    lab, out, *excl = sys.argv[1:]
    skip = set()
    for f in excl:
        for line in open(f):
            m = re.match(r'(\w+)\s+equ\b', line, re.I)
            if m:
                skip.add(m.group(1).upper())
    lines = ['* generated by tools/mads2icl.py from %s' % lab]
    for line in open(lab):
        f = line.split()
        if len(f) == 3 and re.fullmatch(r'[0-9A-F]{2}', f[0]) and f[2].upper() not in skip:
            lines.append('%-12s equ $%s' % (f[2], f[1]))
    open(out, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
