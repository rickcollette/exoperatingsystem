#!/usr/bin/env python3
"""Generate gefina.asm from gefina.txt and assemble GEFINA.COM.

Each line of gefina.txt is a file specification. GEFINA.COM calls U_GEFINA
on each and stores device (1), name (11) and path (64) at $9000 + 80 * i;
CURDEV at the start goes to $8FFF. A spec that makes U_GEFINA fail ends
the program, so put such a spec last.
"""
import subprocess
from pathlib import Path

here = Path(__file__).resolve().parent
specs = (here / 'gefina.txt').read_text().split('\n')[:-1]
n = len(specs)

out = ["; generated by tools/probe/mkgefina.py: U_GEFINA on each spec, results at $9000",
       "U_GEFINA smb 'U_GEFINA'",
       "FILE_P   smb 'FILE_P'",
       "CURDEV   smb 'CURDEV'",
       "        blk reloc main",
       "start   lda CURDEV",
       "        sta $8FFF",
       "        ldy #0",
       "        ldx #0",
       "        stx count",
       "loop    sty idx",
       "        lda strs,y",
       "        ldx strs+1,y",
       "        jsr one",
       "        ldy idx",
       "        iny",
       "        iny",
       "        cpy #%d" % (2 * n),
       "        bne loop",
       "        rts",
       "one     sta FILE_P",
       "        stx FILE_P+1",
       "        lda #$AA",
       "        ldx #63",
       "clr     sta $07A0,x",
       "        cpx #12",
       "        bcs clr1",
       "        sta $0761,x",
       "clr1    dex",
       "        bpl clr",
       "        jsr U_GEFINA",
       "        ldx count",
       "        lda dst,x",
       "        sta to+1",
       "        lda dst+1,x",
       "        sta to+2",
       "        ldx #0",
       "cp      lda $0761,x",
       "to      sta $FFFF,x",
       "        inx",
       "        cpx #12",
       "        bne cp",
       "        lda to+1",
       "        clc",
       "        adc #12",
       "        sta to2+1",
       "        lda to+2",
       "        adc #0",
       "        sta to2+2",
       "        ldx #0",
       "cp2     lda $07A0,x",
       "to2     sta $FFFF,x",
       "        inx",
       "        cpx #64",
       "        bne cp2",
       "        inc count",
       "        inc count",
       "        rts",
       "count   dta 0",
       "idx     dta 0",
       "strs"]
out += ["        dta a(s%d)" % i for i in range(n)]
out += ["", "dst"]
out += ["        dta a($9000+%d)" % (80 * i) for i in range(n)]
for i, s in enumerate(specs):
    out.append("s%-6d dta c'%s',b($9B)" % (i, s))
out += ["        blk update address", "        blk update symbols", ""]
(here / 'gefina.asm').write_text('\n'.join(out))
subprocess.run(['mads', 'gefina.asm', '-o:GEFINA.COM'], cwd=here, check=True)
