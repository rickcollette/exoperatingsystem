#!/usr/bin/env python3
"""Build the ROM symbol table from eos/symbols.txt and the label tables.

usage: mksymtab.py symbols.txt labeldir out.icl
"""
import sys
from pathlib import Path


def labels(path):
    out = {}
    for line in Path(path).read_text().splitlines():
        f = line.split()
        if len(f) == 3:
            out[f[2].upper()] = int(f[1], 16)
    return out


def main():
    src, labdir, out = sys.argv[1:4]
    tabs = {}
    lines = ['* generated by tools/mksymtab.py from %s' % src]
    for line in Path(src).read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        name, module, label = line.split()
        if module not in tabs:
            tabs[module] = labels(Path(labdir) / (module + '.lab'))
        addr = tabs[module].get(label.upper())
        if addr is None:
            sys.exit('mksymtab: %s: no label %s in %s' % (name, label, module))
        lines.append("        dta c'%-8s',a($%04X)" % (name, addr))
    Path(out).write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
